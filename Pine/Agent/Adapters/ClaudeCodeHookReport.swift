import Foundation

/// Reporting-plane model for user-launched Claude terminal sessions.
///
/// Hooks are REPORTING-ONLY: an ambient hook response has no approval or
/// execution authority, and a hook event can never grant control to
/// unrelated terminal output, answer an approval, or relabel another
/// launch/session. Unless a separately reviewed control contract exists,
/// reports are observations.
///
/// Threat model (same-user/agent spoofing): a session ID or hook token
/// visible to the agent is not independent proof against that agent. Any
/// process running under the same user — including the agent itself — can
/// forge a report. Reports therefore never create current blocked, idle, or
/// Ready state on their own; spooled or replayed reports are marked
/// historical, and lost lifecycle evidence makes execution unknown.
nonisolated enum ClaudeCodeHookError: Error, Equatable, Sendable {
    case invalidEvent
    case invalidIdentity
    case invalidSession
    case invalidToolName
    case globalSettingsRefused
    case invalidEndpoint
}

/// The bounded set of lifecycle events Pine records from user-launched
/// sessions. Every other hook event is rejected, not downgraded.
nonisolated enum ClaudeCodeHookEvent: String, CaseIterable, Sendable {
    case sessionStart = "SessionStart"
    case sessionEnd = "SessionEnd"
    case userPromptSubmit = "UserPromptSubmit"
    case preToolUse = "PreToolUse"
    case postToolUse = "PostToolUse"
    case postToolUseFailure = "PostToolUseFailure"
    case stop = "Stop"
    case stopFailure = "StopFailure"
    case notification = "Notification"
}

/// Delivery identity for one Pine-observed launch. The token is generated by
/// Pine at launch and is not an authentication boundary against the agent
/// (it is visible to the same user); it only binds a report to the exact
/// launch and session Pine expects.
nonisolated struct ClaudeCodeHookLaunchIdentity: Equatable, Sendable {
    let launchToken: String
    let sessionID: String

    init(launchToken: String, sessionID: String) throws {
        guard launchToken.utf8.count >= 16, launchToken.utf8.count <= 256,
              launchToken.unicodeScalars.allSatisfy({ (97...122).contains($0.value)
                  || (65...90).contains($0.value) || (48...57).contains($0.value)
                  || $0.value == 45 || $0.value == 95 || $0.value == 46 }) else {
            throw ClaudeCodeHookError.invalidIdentity
        }
        self.launchToken = launchToken
        self.sessionID = try Self.validateSession(sessionID)
    }

    static func validateSession(_ value: String) throws -> String {
        guard !value.isEmpty, value.utf8.count <= 128,
              !value.unicodeScalars.contains(where: CharacterSet.controlCharacters.contains) else {
            throw ClaudeCodeHookError.invalidSession
        }
        return value
    }
}

/// One allowlisted report. The struct deliberately has no fields for prompts,
/// `tool_input`, assistant text, transcript contents, environment values,
/// credentials, or secret-bearing paths: retention is by construction, not
/// by redaction.
nonisolated struct ClaudeCodeHookReport: Equatable, Sendable {
    let event: ClaudeCodeHookEvent
    let sessionID: String
    let launchToken: String
    let toolName: String?
    let subagent: Bool
    /// Set when the report arrives from a spool or replay rather than live
    /// delivery. Historical reports cannot create current blocked, idle, or
    /// Ready state.
    let historical: Bool

    init(event: ClaudeCodeHookEvent, sessionID: String, launchToken: String,
         toolName: String? = nil, subagent: Bool = false, historical: Bool = false) throws {
        self.event = event
        self.sessionID = try ClaudeCodeHookLaunchIdentity.validateSession(sessionID)
        self.launchToken = launchToken
        self.toolName = try toolName.map { name in
            guard !name.isEmpty, name.utf8.count <= 128,
                  !name.unicodeScalars.contains(where: CharacterSet.controlCharacters.contains) else {
                throw ClaudeCodeHookError.invalidToolName
            }
            return name
        }
        self.subagent = subagent
        self.historical = historical
    }

    static let toolOnlyEvents: Set<ClaudeCodeHookEvent> = [
        .preToolUse, .postToolUse, .postToolUseFailure
    ]

    var isToolEvent: Bool { Self.toolOnlyEvents.contains(event) }
}

nonisolated enum ClaudeCodeHookReportRejection: Error, Equatable, Sendable {
    case unauthenticated
    case foreignSession
    case foreignLaunch
    case nested
    case stale
    case unsupportedEvent
    case missingToolName
}

/// Validates a report against one launch identity. The validator is
/// stateless per launch: it remembers only that the session ended, so a
/// report after `SessionEnd` is stale.
nonisolated struct ClaudeCodeHookReportValidator: Sendable {
    private let identity: ClaudeCodeHookLaunchIdentity
    private var sessionEnded = false

    init(identity: ClaudeCodeHookLaunchIdentity) {
        self.identity = identity
    }

    mutating func validate(_ report: ClaudeCodeHookReport) -> Result<ClaudeCodeHookReport, ClaudeCodeHookReportRejection> {
        guard report.launchToken == identity.launchToken else {
            return .failure(.foreignLaunch)
        }
        guard report.sessionID == identity.sessionID else {
            return .failure(.foreignSession)
        }
        guard !report.subagent else { return .failure(.nested) }
        guard report.event != .sessionStart || !sessionEnded else {
            return .failure(.stale)
        }
        if report.event == .sessionEnd {
            sessionEnded = true
            return .success(report)
        }
        guard !sessionEnded else { return .failure(.stale) }
        if report.isToolEvent, report.toolName == nil {
            return .failure(.missingToolName)
        }
        return .success(report)
    }
}

/// Parses the bounded hook envelope delivered to Pine. Everything outside the
/// allowlist is dropped at the boundary, including `transcript_path`, `cwd`,
/// `prompt`, `tool_input`, and any environment values.
nonisolated enum ClaudeCodeHookEnvelope {
    static func parse(
        data: Data,
        historical: Bool = false
    ) -> Result<ClaudeCodeHookReport, ClaudeCodeHookReportRejection> {
        var parser = AgentEventJSONParser(data: data)
        guard case .object(let fields) = try? parser.parse(),
              case .string(let eventName) = fields["hook_event_name"],
              let event = ClaudeCodeHookEvent(rawValue: eventName) else {
            return .failure(.unsupportedEvent)
        }
        guard case .string(let sessionID) = fields["session_id"],
              case .string(let token) = fields["launch_token"], !token.isEmpty else {
            return .failure(.unauthenticated)
        }
        let agentID: String?
        if let rawAgent = fields["agent_id"] {
            guard case .string(let value) = rawAgent else { return .failure(.unauthenticated) }
            agentID = value.isEmpty ? nil : value
        } else {
            agentID = nil
        }
        var toolName: String?
        if let rawTool = fields["tool_name"] {
            guard case .string(let value) = rawTool else { return .failure(.unsupportedEvent) }
            toolName = value
        }
        do {
            let report = try ClaudeCodeHookReport(
                event: event, sessionID: sessionID, launchToken: token,
                toolName: toolName, subagent: agentID != nil, historical: historical
            )
            return .success(report)
        } catch {
            return .failure(.unauthenticated)
        }
    }
}

/// The consent flow for installing Pine's hook. Explicit consent plus a
/// preview precede installation; the plan can only target the project-local
/// `settings.local.json`, never the global `~/.claude/settings.json` or
/// managed policy settings.
nonisolated struct ClaudeCodeHookInstallationPlan: Equatable, Sendable {
    /// Project-local only. Global or managed targets are refused at
    /// construction, so a silent global change is unrepresentable.
    let targetRelativePath: String
    let events: [ClaudeCodeHookEvent]
    let preview: String

    enum TargetError: Error { case global }

    init(events: [ClaudeCodeHookEvent], targetRelativePath: String = ".claude/settings.local.json") throws {
        guard !events.isEmpty, targetRelativePath == ".claude/settings.local.json" else {
            throw TargetError.global
        }
        self.events = Array(Set(events)).sorted { $0.rawValue < $1.rawValue }
        self.targetRelativePath = targetRelativePath
        self.preview = try Self.renderPreview(events: self.events, target: targetRelativePath)
    }

    private static func renderPreview(
        events: [ClaudeCodeHookEvent],
        target: String
    ) throws -> String {
        var lines: [String] = [
            "# Preview of the hook installation (no global settings are modified)",
            "target: \(target)",
            "events:"
        ]
        for event in events {
            lines.append("  - \(event.rawValue) (reporting only; no approval authority)")
        }
        lines.append("delivery: local Pine receiver, bound to the exact launch and session")
        return lines.joined(separator: "\n")
    }
}
